#!/usr/bin/env node
// parser-generator.js - Parser source generator from EBNF grammar

const fs = require('fs');
const path = require('path');
const GrammarParser = require('./grammar-parser');
const CodeGenerator = require('./code-generator');

async function main() {
  const rawArgs = process.argv.slice(2);
  const args = [];
  let language = 'javascript';

  for (let index = 0; index < rawArgs.length; index += 1) {
    const arg = rawArgs[index];
    if (arg === '--language') {
      language = rawArgs[index + 1] || '';
      index += 1;
    } else if (arg.startsWith('--language=')) {
      language = arg.slice('--language='.length);
    } else {
      args.push(arg);
    }
  }

  if (!['javascript', 'cpp98'].includes(language)) {
    console.error(`Unsupported output language: ${language}`);
    process.exit(1);
  }
  
  if (args.length < 1) {
    console.log(`
Usage: node parser-generator.js <grammar-xml-file> [output-file]

Options:
  --language <name>  Parser output language: javascript (default) or cpp98
  grammar-xml-file   XML file generated by REx from EBNF grammar
  output-file        Optional output file (default depends on language)

Example:
  node parser-generator.js grammar.xml my-parser.js
  node parser-generator.js --language cpp98 grammar.xml my-parser.cpp
`);
    process.exit(1);
  }
  
  const inputFile = args[0];
  const outputFile = args[1] || (language === 'cpp98' ? 'parser.cpp' : 'parser.js');
  
  console.log(`📖 Reading grammar XML from: ${inputFile}`);
  
  try {
    const xmlContent = fs.readFileSync(inputFile, 'utf8');
    
    console.log('🔍 Parsing grammar structure...');
    const grammarParser = new GrammarParser(xmlContent);
    const grammar = await grammarParser.parse();
    
    console.log(`📊 Found ${grammar.rules.size} syntax rules and ${grammar.tokens.size} lexical rules`);
    console.log(`🎯 Start symbol: ${grammar.startSymbol}`);
    
    console.log(`⚙️  Generating ${language} parser...`);
    const generator = new CodeGenerator(grammar, { language });
    const parserCode = generator.generate();
    
    fs.writeFileSync(outputFile, parserCode, 'utf8');
    console.log(`✅ Parser generated successfully: ${outputFile}`);
    
  } catch (error) {
    console.error('❌ Error:', error.message);
    console.error(error.stack);
    process.exit(1);
  }
}

// If executed directly, run the main function
if (require.main === module) {
  main();
}

module.exports = { GrammarParser, CodeGenerator };